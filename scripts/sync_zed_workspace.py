#!/usr/bin/env python3
"""Regenerate this Cargo workspace's manifest from a Zed checkout.

Zed crates are consumed as git dependencies pinned to one revision. The local
workspace members inherit dependencies from this root, so keep only the entries
they reference. Git dependencies inherit from Zed's own workspace manifest.
Cargo also applies the root `[patch]` tables to the full dependency graph.

Usage: sync_zed_workspace.py <zed-checkout>
Copies Zed's Cargo.lock as the starting point for dependency resolution.
"""

import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ZED_GIT = "https://github.com/zed-industries/zed"
HERE = Path(__file__).resolve().parent.parent

# Zed crates vendored under third_party/ because they need iOS patches.
VENDORED = ["fs", "settings"]

HEADER = """# Generated by scripts/sync_zed_workspace.py from Zed {rev}. Do not edit by hand.

[workspace]
resolver = "2"
members = [
    "packages/gpui_ios",
    "packages/gpui_macos",
    "packages/zed-gpui-c-api",
    "third_party/trash-rs",
{vendored_members}]

[workspace.package]
publish = false
edition = "2024"

"""

PATCH_ZED = """
# Route every Zed crate's dependency on gpui_macos and gpui_ios to the vendored copies with the
# hosted view mode.
[patch."{git}"]
gpui_ios = {{ path = "packages/gpui_ios" }}
gpui_macos = {{ path = "packages/gpui_macos" }}
# Copies of Zed crates patched for iOS (see third_party/README.md).
{vendored_patches}
[patch."https://github.com/zed-industries/trash-rs"]
trash = {{ path = "third_party/trash-rs" }}

"""


def section(text: str, header: str) -> str:
    match = re.search(rf"^\[{re.escape(header)}\]\n(.*?)(?=^\[)", text, re.S | re.M)
    if not match:
        raise SystemExit(f"missing [{header}] in Zed Cargo.toml")
    return f"[{header}]\n{match.group(1)}"


def local_workspace_dependencies() -> set[str]:
    dependencies = set()
    for manifest in [
        *(HERE / "packages").glob("*/Cargo.toml"),
        *(HERE / "third_party").glob("*/Cargo.toml"),
    ]:
        package = tomllib.loads(manifest.read_text())
        tables = [
            package.get("dependencies", {}),
            package.get("dev-dependencies", {}),
            package.get("build-dependencies", {}),
        ]
        for target in package.get("target", {}).values():
            tables.extend(
                target.get(table, {})
                for table in ("dependencies", "dev-dependencies", "build-dependencies")
            )
        for table in tables:
            dependencies.update(
                name
                for name, definition in table.items()
                if isinstance(definition, dict) and definition.get("workspace") is True
            )
    return dependencies


def filter_workspace_dependencies(table: str, needed: set[str], zed_manifest: str) -> str:
    definitions = tomllib.loads(zed_manifest)["workspace"]["dependencies"]
    missing = needed - definitions.keys()
    if missing:
        raise SystemExit(f"missing workspace dependency definitions: {', '.join(sorted(missing))}")

    starts = list(re.finditer(r"^([A-Za-z0-9_-]+)\s*=", table, re.M))
    retained = ["[workspace.dependencies]\n"]
    for index, match in enumerate(starts):
        name = match.group(1)
        end = starts[index + 1].start() if index + 1 < len(starts) else len(table)
        if name in needed:
            retained.append(table[match.start() : end].rstrip() + "\n")
    # Dependencies that Zed spells as a `[workspace.dependencies.<name>]` table.
    for name in sorted(needed):
        subtable = re.search(
            rf"^\[workspace\.dependencies\.{re.escape(name)}\]\n(.*?)(?=^\[|\Z)",
            zed_manifest,
            re.S | re.M,
        )
        if subtable:
            retained.append(f"\n[workspace.dependencies.{name}]\n{subtable.group(1).rstrip()}\n")
    return "".join(retained)


def main() -> None:
    zed = Path(sys.argv[1]).resolve()
    rev = subprocess.check_output(["git", "-C", str(zed), "rev-parse", "HEAD"], text=True).strip()
    text = (zed / "Cargo.toml").read_text()

    def pin_to_git(table: str) -> str:
        return re.sub(
            r'path = "(?:crates|tooling)/[^"]+"', f'git = "{ZED_GIT}", rev = "{rev}"', table
        )

    workspace_dependencies = pin_to_git(section(text, "workspace.dependencies"))
    workspace_dependencies = filter_workspace_dependencies(
        workspace_dependencies, local_workspace_dependencies(), text
    )

    parts = [
        HEADER.format(
            rev=rev,
            vendored_members="".join(f'    "third_party/{name}",\n' for name in VENDORED),
        ),
        workspace_dependencies,
        PATCH_ZED.format(
            git=ZED_GIT,
            vendored_patches="".join(
                f'{name} = {{ path = "third_party/{name}" }}\n' for name in VENDORED
            ),
        ),
        pin_to_git(section(text, "patch.crates-io")),
        section(text, "profile.dev"),
        section(text, "profile.dev.build-override"),
        section(text, "profile.dev.package"),
        section(text, "workspace.lints.rust"),
        section(text, "workspace.lints.clippy"),
    ]
    (HERE / "Cargo.toml").write_text("".join(parts).rstrip() + "\n")
    shutil.copyfile(zed / "Cargo.lock", HERE / "Cargo.lock")
    toolchain = (zed / "rust-toolchain.toml").read_text()
    channel = re.search(r'channel = "([^"]+)"', toolchain).group(1)
    (HERE / "rust-toolchain.toml").write_text(
        f'[toolchain]\nchannel = "{channel}"\nprofile = "minimal"\n'
    )
    print(f"synced Zed {rev} (toolchain {channel})")


if __name__ == "__main__":
    main()
